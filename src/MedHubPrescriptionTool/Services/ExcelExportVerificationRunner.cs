using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;
using System.Threading.Tasks;
using ClosedXML.Excel;
using MedHubPrescriptionTool.Configuration;
using MedHubPrescriptionTool.Data;
using MedHubPrescriptionTool.Models;

namespace MedHubPrescriptionTool.Services;

/// <summary>
/// Self-testing automated verification runner for Milestone 3.
/// Validates ClosedXML workbook generation, 2-sheet layout, 17 and 16 column schema contracts,
/// text preservation of leading zeros (MRN and Case No), date/number formatting, visual styling,
/// and disk file export capabilities.
/// </summary>
public static class ExcelExportVerificationRunner
{
    public static async Task<int> RunAsync()
    {
        Console.WriteLine("================================================================================");
        Console.WriteLine(" MedHub DB Prescription Tool - Milestone 3 Verification Suite");
        Console.WriteLine(" Smart Multi-Sheet Excel Export Engine (ClosedXML)");
        Console.WriteLine("================================================================================");

        var config = AppConfigurationManager.Current;
        var factory = new DatabaseConnectionFactory(config.Database);
        var repo = new DatabaseRepository(factory);
        var clinicalService = new ClinicalDataService(repo);
        var excelService = new ExcelExportService();

        int passed = 0;
        int failed = 0;

        void AssertPass(string testName, string details)
        {
            Console.ForegroundColor = ConsoleColor.Green;
            Console.Write("[PASS] ");
            Console.ResetColor();
            Console.WriteLine($"{testName}: {details}");
            passed++;
        }

        void AssertFail(string testName, string error)
        {
            Console.ForegroundColor = ConsoleColor.Red;
            Console.Write("[FAIL] ");
            Console.ResetColor();
            Console.WriteLine($"{testName}: {error}");
            failed++;
        }

        ClinicalDataSnapshot? snapshot = null;
        byte[]? liveExcelBytes = null;

        // Test 1: Generate Live Workbook from Consolidated Snapshot
        try
        {
            snapshot = await clinicalService.LoadClinicalSnapshotAsync();

            var sw = Stopwatch.StartNew();
            liveExcelBytes = excelService.GenerateMultiSheetExcel(
                snapshot.MarSchedules,
                snapshot.ActivePrescriptions,
                "MedHub Inpatient Clinical Administration");
            sw.Stop();

            if (liveExcelBytes != null && liveExcelBytes.Length > 8192)
            {
                AssertPass("1. Live Workbook Generation",
                    $"Generated {liveExcelBytes.Length:N0} bytes in {sw.ElapsedMilliseconds}ms for {snapshot.MarSchedules.Count} MAR items and {snapshot.ActivePrescriptions.Count} active prescriptions (> 8 KB threshold passed)");
            }
            else
            {
                AssertFail("1. Live Workbook Generation",
                    $"Generated byte stream is too small or null: {liveExcelBytes?.Length ?? 0} bytes (expected > 8,192 bytes)");
                return 1;
            }
        }
        catch (Exception ex)
        {
            AssertFail("1. Live Workbook Generation", ex.Message);
            return 1;
        }

        // Test 2: Worksheet Count and Exact Names
        try
        {
            using var ms = new MemoryStream(liveExcelBytes);
            using var wb = new XLWorkbook(ms);

            bool sheetCountValid = wb.Worksheets.Count == 2;
            bool sheet1Exists = wb.Worksheets.Contains("MAR Schedule & Dispense Log");
            bool sheet2Exists = wb.Worksheets.Contains("Active Prescriptions Overview");

            if (sheetCountValid && sheet1Exists && sheet2Exists)
            {
                AssertPass("2. Worksheet Names & Structure",
                    $"Verified 2 worksheets: [Sheet 1: '{wb.Worksheet(1).Name}', Sheet 2: '{wb.Worksheet(2).Name}']");
            }
            else
            {
                var names = string.Join(", ", wb.Worksheets.Select(w => $"'{w.Name}'"));
                AssertFail("2. Worksheet Names & Structure",
                    $"Sheets mismatch. Count: {wb.Worksheets.Count} (exp 2). Worksheets found: [{names}]");
            }
        }
        catch (Exception ex)
        {
            AssertFail("2. Worksheet Names & Structure", ex.Message);
        }

        // Test 3: Sheet 1 Schema & 17 Standard Clinical Columns
        try
        {
            using var ms = new MemoryStream(liveExcelBytes);
            using var wb = new XLWorkbook(ms);
            var sheet1 = wb.Worksheet("MAR Schedule & Dispense Log");

            string[] expectedSheet1Headers =
            [
                "Patient MRN",
                "Patient Name",
                "Care Station",
                "Bed",
                "Medication Code",
                "Display Name",
                "Generic Name",
                "Dose Ordered",
                "Unit",
                "Frequency",
                "Route",
                "Scheduled Date & Time",
                "Dispense Status",
                "Dispensed Qty",
                "Status Time",
                "Dispensing Nurse",
                "Witnessing Nurse / Notes"
            ];

            bool headersMatch = true;
            var mismatchedCol = string.Empty;

            for (int col = 1; col <= 17; col++)
            {
                string headerVal = sheet1.Cell(4, col).GetString().Trim();
                if (!string.Equals(headerVal, expectedSheet1Headers[col - 1], StringComparison.Ordinal))
                {
                    headersMatch = false;
                    mismatchedCol = $"Col {col}: Found '{headerVal}', Expected '{expectedSheet1Headers[col - 1]}'";
                    break;
                }
            }

            var bannerVal = sheet1.Cell(1, 1).GetString();
            var subBannerVal = sheet1.Cell(2, 1).GetString();
            bool bannerValid = bannerVal.Contains("MEDHUB CLINICAL INPATIENT MEDICATION ADMINISTRATION & DISPENSE LOG") &&
                               subBannerVal.Contains("Total Scheduled Administrations: 385");

            if (headersMatch && bannerValid)
            {
                AssertPass("3. Sheet 1 Schema & Headers",
                    $"Verified all 17 column headers and Medical Teal clinical title banners on 'MAR Schedule & Dispense Log'");
            }
            else
            {
                AssertFail("3. Sheet 1 Schema & Headers",
                    headersMatch ? "Banner text mismatch." : mismatchedCol);
            }
        }
        catch (Exception ex)
        {
            AssertFail("3. Sheet 1 Schema & Headers", ex.Message);
        }

        // Test 4: Sheet 2 Schema & 16 Active Prescription Columns
        try
        {
            using var ms = new MemoryStream(liveExcelBytes);
            using var wb = new XLWorkbook(ms);
            var sheet2 = wb.Worksheet("Active Prescriptions Overview");

            string[] expectedSheet2Headers =
            [
                "Patient MRN",
                "Patient Name",
                "Case Number",
                "Care Station",
                "Bed",
                "Attending Physician",
                "Medication Code",
                "Display Name",
                "Dosage Ordered & Unit",
                "Frequency",
                "Route",
                "Clinical Indication",
                "Order Start Time",
                "Order End Time",
                "Total Scheduled Doses",
                "Order Status"
            ];

            bool headersMatch = true;
            var mismatchedCol = string.Empty;

            for (int col = 1; col <= 16; col++)
            {
                string headerVal = sheet2.Cell(4, col).GetString().Trim();
                if (!string.Equals(headerVal, expectedSheet2Headers[col - 1], StringComparison.Ordinal))
                {
                    headersMatch = false;
                    mismatchedCol = $"Col {col}: Found '{headerVal}', Expected '{expectedSheet2Headers[col - 1]}'";
                    break;
                }
            }

            var bannerVal = sheet2.Cell(1, 1).GetString();
            var subBannerVal = sheet2.Cell(2, 1).GetString();
            bool bannerValid = bannerVal.Contains("MEDHUB ACTIVE INPATIENT PRESCRIPTIONS & CLINICAL REGIMENS") &&
                               subBannerVal.Contains("Total Active Orders: 31");

            if (headersMatch && bannerValid)
            {
                AssertPass("4. Sheet 2 Schema & Headers",
                    $"Verified all 16 column headers and clinical title banners on 'Active Prescriptions Overview'");
            }
            else
            {
                AssertFail("4. Sheet 2 Schema & Headers",
                    headersMatch ? "Banner text mismatch." : mismatchedCol);
            }
        }
        catch (Exception ex)
        {
            AssertFail("4. Sheet 2 Schema & Headers", ex.Message);
        }

        // Test 5: Leading Zero Preservation & Numeric Formats
        try
        {
            using var ms = new MemoryStream(liveExcelBytes);
            using var wb = new XLWorkbook(ms);
            var sheet1 = wb.Worksheet("MAR Schedule & Dispense Log");
            var sheet2 = wb.Worksheet("Active Prescriptions Overview");

            // In our live snapshot, patient Chen, Wei has MRN "00075655" and patient Teng, Max has MRN "0439449"
            bool foundLeadingZeroMrn = false;
            string foundMrn = string.Empty;

            for (int row = 5; row <= 5 + snapshot.MarSchedules.Count; row++)
            {
                var cell = sheet1.Cell(row, 1);
                string strVal = cell.GetString();
                if (strVal.StartsWith('0') && strVal.Length > 1)
                {
                    foundLeadingZeroMrn = true;
                    foundMrn = strVal;

                    if (cell.DataType != XLDataType.Text || cell.Style.NumberFormat.Format != "@")
                    {
                        AssertFail("5. Leading Zero Preservation",
                            $"Cell A{row} has value '{strVal}' but DataType={cell.DataType} (exp Text) or Format='{cell.Style.NumberFormat.Format}' (exp '@')");
                        foundLeadingZeroMrn = false;
                        break;
                    }
                }
            }

            // Verify Dose Ordered column is numeric
            var doseCell = sheet1.Cell(5, 8);
            bool doseNumeric = doseCell.DataType == XLDataType.Number && doseCell.Style.NumberFormat.Format == "#,##0.00";

            // Verify Sheet 2 Case Number has text format
            var caseCell = sheet2.Cell(5, 3);
            bool caseText = caseCell.DataType == XLDataType.Text && caseCell.Style.NumberFormat.Format == "@";

            if (foundLeadingZeroMrn && doseNumeric && caseText)
            {
                AssertPass("5. Leading Zero & Type Preservation",
                    $"Preserved leading zeros for MRN '{foundMrn}' as Text '@', Case No as Text '@', and Dose Ordered as Number '#,##0.00'");
            }
            else
            {
                AssertFail("5. Leading Zero & Type Preservation",
                    $"Leading zero check: Found={foundLeadingZeroMrn}, DoseNumeric={doseNumeric} ({doseCell.DataType}), CaseText={caseText} ({caseCell.DataType})");
            }
        }
        catch (Exception ex)
        {
            AssertFail("5. Leading Zero & Type Preservation", ex.Message);
        }

        // Test 6: Row Counts, Freeze Panes, and Visual Styling
        try
        {
            using var ms = new MemoryStream(liveExcelBytes);
            using var wb = new XLWorkbook(ms);
            var sheet1 = wb.Worksheet("MAR Schedule & Dispense Log");
            var sheet2 = wb.Worksheet("Active Prescriptions Overview");

            // Row 4 is header, data rows start at row 5
            int sheet1LastDataRow = sheet1.LastRowUsed()?.RowNumber() ?? 0;
            int sheet2LastDataRow = sheet2.LastRowUsed()?.RowNumber() ?? 0;

            int sheet1RowCount = sheet1LastDataRow - 4; // Minus 4 header/banner rows
            int sheet2RowCount = sheet2LastDataRow - 4;

            bool rowCountsMatch = sheet1RowCount == snapshot.MarSchedules.Count &&
                                  sheet2RowCount == snapshot.ActivePrescriptions.Count;

            // Verify FreezeRows is set to 4
            var sheet1FreezeValid = sheet1.SheetView.SplitRow == 4;
            var sheet2FreezeValid = sheet2.SheetView.SplitRow == 4;

            if (rowCountsMatch && sheet1FreezeValid && sheet2FreezeValid)
            {
                AssertPass("6. Row Counts & Freeze Panes",
                    $"Sheet 1: {sheet1RowCount} data rows (exp {snapshot.MarSchedules.Count}), Sheet 2: {sheet2RowCount} data rows (exp {snapshot.ActivePrescriptions.Count}), FreezeRows=4 verified on both sheets");
            }
            else
            {
                AssertFail("6. Row Counts & Freeze Panes",
                    $"Row counts mismatch: Sheet 1 rows={sheet1RowCount} (exp {snapshot.MarSchedules.Count}, Freeze={sheet1FreezeValid}), Sheet 2 rows={sheet2RowCount} (exp {snapshot.ActivePrescriptions.Count}, Freeze={sheet2FreezeValid})");
            }
        }
        catch (Exception ex)
        {
            AssertFail("6. Row Counts & Freeze Panes", ex.Message);
        }

        // Test 7: Standardized Filename Generation
        try
        {
            var defaultName = excelService.GenerateTimestampedFilename();
            var customPrefix = excelService.GenerateTimestampedFilename("MedHub_ShiftReport");

            var regex = new Regex(@"^MedHub_Prescriptions_\d{8}_\d{4}\.xlsx$");
            var customRegex = new Regex(@"^MedHub_ShiftReport_\d{8}_\d{4}\.xlsx$");

            if (regex.IsMatch(defaultName) && customRegex.IsMatch(customPrefix))
            {
                AssertPass("7. Filename Generation Pattern",
                    $"Generated compliant filenames: '{defaultName}' and '{customPrefix}' matching MedHub_Prescriptions_YYYYMMDD_HHmm.xlsx");
            }
            else
            {
                AssertFail("7. Filename Generation Pattern",
                    $"Generated filename pattern invalid: '{defaultName}' or '{customPrefix}'");
            }
        }
        catch (Exception ex)
        {
            AssertFail("7. Filename Generation Pattern", ex.Message);
        }

        // Test 8: Asynchronous File Export to Disk
        try
        {
            string tempDir = Path.Combine(Path.GetTempPath(), "MedHubExcelExportTest_" + Guid.NewGuid().ToString("N")[..8]);
            string savedPath = await excelService.ExportToFileAsync(
                tempDir,
                snapshot.MarSchedules,
                snapshot.ActivePrescriptions);

            bool fileExists = File.Exists(savedPath);
            long fileBytes = fileExists ? new FileInfo(savedPath).Length : 0;

            // Clean up
            if (Directory.Exists(tempDir))
            {
                Directory.Delete(tempDir, true);
            }

            if (fileExists && fileBytes > 8192)
            {
                AssertPass("8. Disk File Export & I/O",
                    $"Exported {fileBytes:N0} bytes to disk at '{Path.GetFileName(savedPath)}' and verified file existence");
            }
            else
            {
                AssertFail("8. Disk File Export & I/O",
                    $"File not created or size too small: {fileBytes} bytes at '{savedPath}'");
            }
        }
        catch (Exception ex)
        {
            AssertFail("8. Disk File Export & I/O", ex.Message);
        }

        // Test 9: Zero Records Export Boundary Handling
        try
        {
            var emptyBytes = excelService.GenerateMultiSheetExcel(
                new List<MarScheduleItemDto>(),
                new List<ActivePrescriptionDto>());

            using var ms = new MemoryStream(emptyBytes);
            using var wb = new XLWorkbook(ms);

            var s1 = wb.Worksheet("MAR Schedule & Dispense Log");
            var s2 = wb.Worksheet("Active Prescriptions Overview");

            bool s1InfoFound = s1.Cell("A5").GetString().Contains("No medication administration records found");
            bool s2InfoFound = s2.Cell("A5").GetString().Contains("No active prescription records found");

            if (emptyBytes.Length > 4000 && s1InfoFound && s2InfoFound)
            {
                AssertPass("9. Empty Records Boundary Safety",
                    $"Zero-records export gracefully rendered informational rows on both worksheets ({emptyBytes.Length:N0} bytes)");
            }
            else
            {
                AssertFail("9. Empty Records Boundary Safety",
                    $"Empty records export failed. Bytes={emptyBytes.Length}, S1Info={s1InfoFound}, S2Info={s2InfoFound}");
            }
        }
        catch (Exception ex)
        {
            AssertFail("9. Empty Records Boundary Safety", ex.Message);
        }

        Console.WriteLine("================================================================================");
        Console.WriteLine($" Summary: {passed} PASSED, {failed} FAILED out of {passed + failed} Tests");
        Console.WriteLine("================================================================================");

        return failed == 0 ? 0 : 1;
    }
}
